def golden_trajectory(doc: dict, fixtures: dict) -> str:
    import grade as grader

    rows = []
    for name in ("clean_accepting", "partial_continuous", "margin_ramp_continuous"):
        document = grader.grade(fixtures[name])
        rows.append(
            {
                "fixture": name,
                "reward": document["reward"],
                "reason": document["reason"],
                "graded_steps_per_seed": document["metric"]["graded_steps_per_seed"],
                "mean_raw": document["metric"]["mean_raw"],
                "half_spread": document["metric"]["half_spread"],
                "separation": document["metric"]["separation"],
                "confidence": document["metric"]["confidence"],
            }
        )
    payload = {
        "banner": BANNER,
        "source": SOURCE_LINE,
        "slot": "OER-05",
        "note": "The reference path through the real gate chain. Reward growth is visible across the three fixtures, so the reward is continuous and never binary.",
        "anchors_state": "absent",
        "anchors_gap": "gap-oer-per-family-anchors-unmeasured",
        "fixture_anchor_pair_is_not_an_anchor": True,
        "steps": rows,
    }
    return json.dumps(payload, indent=2, sort_keys=True) + "\n"


