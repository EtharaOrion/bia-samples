def artifacts() -> dict:
    doc = source()
    fixtures = fixture_set(doc)
    out = {}
    for name, payload in sorted(fixtures.items()):
        out[FIXTURES / (name + ".json")] = json.dumps(payload, indent=2, sort_keys=True) + "\n"
    golden_text = golden_trajectory(doc, fixtures)
    out[SOLUTION / "golden_trajectory.json"] = golden_text
    out[SOLUTION / "solve.sh"] = solve_sh(doc)
    out[SOLUTION / "TRUTH.md"] = truth_md(doc, fixtures, json.loads(golden_text))
    out[SOLUTION / "rubrics.json"] = rubrics_json(doc)
    out[TESTS / "test_output.py"] = test_output_py(doc)
    return out


def main(argv) -> int:
    check = "--check" in argv
    rows = artifacts()
    drifted = []
    for path, text in sorted(rows.items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current != text:
            drifted.append(path.relative_to(BUNDLE).as_posix())
            if not check:
                path.write_text(text, encoding="utf-8")
    if check:
        if drifted:
            print("DRIFTED: " + ", ".join(sorted(drifted)))
            return 1
        print("byte-identical over " + str(len(rows)) + " generated artifact(s)")
        return 0
    (SOLUTION / "solve.sh").chmod(0o755)
    print("wrote " + str(len(rows)) + " generated artifact(s); " + str(len(drifted)) + " moved")
    return 0


