def mutate(base: dict, apply) -> dict:
    row = json.loads(json.dumps(base, sort_keys=True))
    apply(row)
    return row


def _plant_truth_before_exit(row):
    row["fixture"] = "defect_truth_before_exit"
    row["order_log"] = [
        {"event": "truth-computed", "seq": 1},
        {"event": "submission-exit", "seq": 2},
        {"event": "process-group-killed", "seq": 3},
    ]


def _plant_grading_tree_mutated(row):
    row["fixture"] = "defect_grading_tree_mutated"
    row["grading_tree"]["digest_close"] = digest_of("grading-tree-moved")
    row["grading_tree"]["upper_entries"] = ["logs/run.jsonl", "tests/checkers.py"]


def _plant_submission_number(row):
    row["fixture"] = "defect_submission_number_on_graded_path"
    row["graded_metric_provenance"][0]["producer"] = "submission"


def _plant_readout_smoothed(row):
    row["fixture"] = "defect_readout_smoothed"
    for run in row["seed_runs"]:
        for point in run["eval_points"]:
            point["smoothing"] = "ema-0.9"
            point["graded_loss"] = round(point["loss_raw"] - 0.05, 6)


def _plant_early_stop(row):
    row["fixture"] = "defect_early_stop"
    for run in row["seed_runs"]:
        run["halt_reason"] = "early-stop"
        cut = int(run["claimed_graded_step"])
        run["eval_points"] = [p for p in run["eval_points"] if p["step"] <= cut]
        run["harness_weight_ledger"] = [p for p in run["harness_weight_ledger"] if p["step"] <= cut]
        run["last_eval_step"] = cut


def _plant_not_sustained(row):
    row["fixture"] = "defect_crossing_not_sustained"
    target = float(row["target_loss"])
    for run in row["seed_runs"]:
        for point in run["eval_points"]:
            if point["step"] > int(run["claimed_graded_step"]):
                point["loss_raw"] = round(target + 0.01, 6)
                point["graded_loss"] = point["loss_raw"]


def _plant_weights_not_owned(row):
    row["fixture"] = "defect_weights_not_harness_owned"
    for run in row["seed_runs"]:
        for point in run["eval_points"]:
            if point["step"] >= int(run["claimed_graded_step"]):
                point["weights_custody"] = "submission-selected-checkpoint"


def _plant_probe_nondeterministic(row):
    row["fixture"] = "defect_probe_nondeterministic"
    rows = json.loads(json.dumps(row["probe"]["pass_b"]["transcript"]))
    rows[0][0] = round(rows[0][0] + 0.001, 6)
    row["probe"]["pass_b"]["transcript"] = rows


def _plant_transcript_divergence(row):
    row["fixture"] = "defect_probe_transcript_diverges"
    row["probe"]["harness_deltas_digest"] = digest_of("harness-watched-something-else")


def _plant_verdict_predates_pin(row):
    row["fixture"] = "defect_novelty_verdict_predates_pin"
    row["verdict_order"] = {"corpus_pinned_at": 5, "verdict_taken_at": 2}


def _plant_stale_probe_set(row):
    row["fixture"] = "control_stale_probe_set"
    row["probe"]["probe_set"] = "probe-set-a"


def _plant_stale_sustain_window(row):
    row["fixture"] = "control_stale_sustain_window"
    target = float(row["target_loss"])
    interval = int(row["eval_interval"])
    for run in row["seed_runs"]:
        crossing = int(run["claimed_graded_step"])
        for point in run["eval_points"]:
            if point["step"] > crossing + 2 * interval:
                point["loss_raw"] = round(target + 0.01, 6)
                point["graded_loss"] = point["loss_raw"]


def _plant_stale_weight_custody(row):
    row["fixture"] = "control_stale_weight_custody"
    for run in row["seed_runs"]:
        for point in run["eval_points"]:
            point["weights_custody"] = "harness-owned"
        for point in run["harness_weight_ledger"]:
            point["custody"] = "harness-owned"


def _plant_anchors_absent(row):
    row["fixture"] = "control_anchors_absent"
    row["anchors"]["state"] = "absent"
    row["anchors"]["baseline_metric"] = None
    row["anchors"]["target_metric"] = None


def fixture_set(doc: dict) -> dict:
    ref_rule = reference.build_update_rule((8, 8), {})
    ref_path = SOLUTION / "reference.py"
    shipped = shipped_rule.build_update_rule((8, 8), {})
    shipped_path = BUNDLE / "environment" / "update_rule.py"

    clean = telemetry(doc, "clean_accepting", ref_rule, rule_path=ref_path)
    clean["fixture"] = "clean_accepting"
    partial = telemetry(doc, "partial_continuous", ref_rule, rule_path=ref_path)
    partial["fixture"] = "partial_continuous"
    ramp = telemetry(doc, "margin_ramp_continuous", ref_rule, rule_path=ref_path)
    ramp["fixture"] = "margin_ramp_continuous"
    floor = telemetry(doc, "separation_below_floor", ref_rule, rule_path=ref_path)
    floor["fixture"] = "defect_separation_below_floor"

    # The unchanged shipped rule. Behaviourally present in the corpus, which is
    # what makes it the no-op negative control rather than a starting point.
    noop = telemetry(doc, "clean_accepting", shipped, rule_path=shipped_path)
    noop["fixture"] = "defect_behaviour_matches_corpus"

    out = {
        "clean_accepting": clean,
        "partial_continuous": partial,
        "margin_ramp_continuous": ramp,
        "defect_separation_below_floor": floor,
        "defect_behaviour_matches_corpus": noop,
    }
    for name, plant in (
        ("defect_truth_before_exit", _plant_truth_before_exit),
        ("defect_grading_tree_mutated", _plant_grading_tree_mutated),
        ("defect_submission_number_on_graded_path", _plant_submission_number),
        ("defect_readout_smoothed", _plant_readout_smoothed),
        ("defect_early_stop", _plant_early_stop),
        ("defect_crossing_not_sustained", _plant_not_sustained),
        ("defect_weights_not_harness_owned", _plant_weights_not_owned),
        ("defect_probe_nondeterministic", _plant_probe_nondeterministic),
        ("defect_probe_transcript_diverges", _plant_transcript_divergence),
        ("defect_novelty_verdict_predates_pin", _plant_verdict_predates_pin),
        ("control_stale_probe_set", _plant_stale_probe_set),
        ("control_stale_sustain_window", _plant_stale_sustain_window),
        ("control_stale_weight_custody", _plant_stale_weight_custody),
        ("control_anchors_absent", _plant_anchors_absent),
    ):
        out[name] = mutate(clean, plant)
    return out


