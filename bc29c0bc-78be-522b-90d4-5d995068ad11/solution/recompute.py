def loss_at(step: int, crossing: int, interval: int, target: float) -> float:
    """A monotone series crossing `target` exactly at `crossing`.

    At `crossing - interval` the value is the target itself, which is NOT below
    it, so the crossing lands where the name says it does and never one point
    early.
    """
    return round(target - (step - crossing + interval) * 0.0002, 6)


def eval_points(seed: int, crossing: int, geo: dict, last_step: int, custody: str) -> list:
    interval = int(geo["eval_interval"])
    target = float(geo["target_loss"])
    rows = []
    for step in range(interval, last_step + 1, interval):
        raw = loss_at(step, crossing, interval, target)
        rows.append(
            {
                "step": step,
                "loss_raw": raw,
                "graded_loss": raw,
                "loss_source": "verifier-holdout-eval",
                "smoothing": "none",
                "weights_digest": digest_of("weights:" + str(seed) + ":" + str(step)),
                "weights_custody": custody,
            }
        )
    return rows


def seed_run(seed: int, crossing: int, geo: dict, last_step: int, custody: str) -> dict:
    points = eval_points(seed, crossing, geo, last_step, custody)
    return {
        "seed": seed,
        "claimed_graded_step": crossing,
        "halt_reason": "completed",
        "last_eval_step": last_step,
        "eval_points": points,
        "harness_weight_ledger": [
            {"step": row["step"], "weights_digest": row["weights_digest"], "custody": custody}
            for row in points
        ],
    }


def probe_block(rule, set_name: str, geo: dict) -> dict:
    """The verifier's own probe outcome over a rule. Computed, never asserted."""
    first = probe.signature(rule, set_name)
    second = probe.signature(rule, set_name)
    signatures = loader.signatures(corpus_rules.build, probe, set_name)
    found = probe.nearest(first["transcript"], signatures)
    pinned = loader.pinned_digest()
    return {
        "probe_set": set_name,
        "pass_a": {"transcript": first["transcript"], "digest": first["digest"]},
        "pass_b": {"transcript": second["transcript"], "digest": second["digest"]},
        "transcript_digest": first["digest"],
        "harness_deltas_digest": first["digest"],
        "corpus_pinned_digest": pinned,
        "corpus_digest_at_verdict": pinned,
        "corpus_entries": len(signatures),
        "behavioural_margin": float(geo["behavioural_margin"]),
        "nearest_corpus_id": found["nearest_corpus_id"],
        "min_behavioural_distance": found["min_behavioural_distance"],
    }


def file_sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def telemetry(doc: dict, steps_key: str, rule, anchors_state: str = "fixture", rule_path: Path = None) -> dict:
    geo = doc["graded_quantity"]
    state = dict(doc["drift_state_final"])
    interval = int(geo["eval_interval"])
    window = int(state["sustain_window"])
    crossings = list(doc["seed_step_lists"][steps_key])
    last_step = max(crossings) + (window + 2) * interval
    pair = doc["fixture_anchor_pair"]
    tree = digest_of("grading-tree-sealed")
    return {
        "schema": checkers.SCHEMA,
        "produced_by": "verifier",
        "fixture": steps_key,
        "drift_state": state,
        "anchors": {
            "state": anchors_state,
            "baseline_metric": pair["baseline_metric"] if anchors_state != "absent" else None,
            "target_metric": pair["target_metric"] if anchors_state != "absent" else None,
            "fixture_only": True,
            "not_an_anchor": True,
            "bound_anchors_state": "absent",
            "bound_anchors_gap": "gap-oer-per-family-anchors-unmeasured",
        },
        "target_loss": float(geo["target_loss"]),
        "eval_interval": interval,
        "seed_runs": [
            seed_run(index, crossing, geo, last_step, state["weight_custody"])
            for index, crossing in enumerate(crossings)
        ],
        "submission_binding": {
            "path": rule_path.relative_to(BUNDLE).as_posix() if rule_path else None,
            "sha256": file_sha256(rule_path) if rule_path else None,
            "note": "the probed rule's bytes, bound into the fixture so the accepting half proves the checkers accept THIS file and not merely some file",
        },
        "probe": probe_block(rule, state["probe_input_set"], geo),
        "order_log": [
            {"event": "submission-exit", "seq": 1},
            {"event": "process-group-killed", "seq": 2},
            {"event": "truth-computed", "seq": 3},
        ],
        "grading_tree": {"digest_open": tree, "digest_close": tree, "upper_entries": ["logs/run.jsonl"]},
        "graded_metric_provenance": [
            {"field": name, "producer": "verifier"} for name in sorted(checkers.GRADED_FIELDS)
        ],
        "verdict_order": {"corpus_pinned_at": 1, "verdict_taken_at": 2},
    }


