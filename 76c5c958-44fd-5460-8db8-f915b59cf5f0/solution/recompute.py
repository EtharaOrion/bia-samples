@contextlib.contextmanager
def scratch(requested):
    """The private scratch tree, relocatable by construction.

    A caller-supplied `--workdir` is honoured as-is and left in place, so an operator can
    inspect the intermediates. With no `--workdir` the scratch is a temporary directory
    removed on exit, so a run leaves nothing behind anywhere -- inside the bundle or
    outside it. Neither path is derived from where the bundle happens to sit.
    """
    if requested is not None:
        path = Path(requested).expanduser().resolve()
        path.mkdir(parents=True, exist_ok=True)
        yield path
        return
    tmp = tempfile.mkdtemp(prefix="oer18_recompute.")
    try:
        yield Path(tmp)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Derive OER-18's generated artifacts.")
    parser.add_argument("--check", action="store_true", help="verify committed bytes, write nothing")
    parser.add_argument(
        "--workdir",
        default=None,
        metavar="DIR",
        help="scratch tree for intermediates; default is a private temp dir removed on exit. "
             "The scratch location never reaches a generated artifact.",
    )
    args = parser.parse_args(argv)

    with scratch(args.workdir) as workdir:
        artifacts = build(workdir)

    drifted = []
    for relative, text in sorted(artifacts.items()):
        path = BUNDLE / relative
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                drifted.append(relative)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")

    for entry in ("solve.sh",):
        target = SOLUTION / entry
        if target.is_file():
            target.chmod(0o755)

    if args.check:
        if drifted:
            print("DRIFTED: " + ", ".join(drifted))
            return 1
        print("clean: " + str(len(artifacts)) + " generated artifacts match their source")
        return 0
    print("wrote " + str(len(artifacts)) + " generated artifacts from solution/grounding.yaml")
    return 0


