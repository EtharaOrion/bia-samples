def handle_for(samples, declared, reported_score, window, params, benchmark, workdir: Path):
    """Drive the REAL grading pipeline over a corpus, so a fixture is never hand-shaped."""
    workdir.mkdir(parents=True, exist_ok=True)
    corpus = workdir / "corpus.jsonl"
    corpus.write_text(
        "".join(json.dumps(row, sort_keys=True) + "\n" for row in samples), encoding="utf-8"
    )
    artifacts = {"corpus": corpus}
    if declared is not None:
        manifest = workdir / "coverage_manifest.json"
        manifest.write_text(json.dumps({"coverage": declared}, indent=2, sort_keys=True), encoding="utf-8")
        artifacts["manifest"] = manifest
    if reported_score is not None or window is not None:
        record = workdir / "run.json"
        record.write_text(
            json.dumps(
                {"reported_benchmark_score": reported_score, "smoothing_window": window},
                indent=2,
                sort_keys=True,
            ),
            encoding="utf-8",
        )
        artifacts["run_record"] = record
    result = runner.RunResult(0, "", "", workdir, artifacts=artifacts)
    return grade.build_handle(result, params, benchmark)


def as_fixture(handle) -> dict:
    return dataclasses.asdict(handle)


def plant(base: dict, **overrides) -> dict:
    row = json.loads(json.dumps(base, sort_keys=True))
    for key, value in overrides.items():
        row[key] = value
    return row


def fixture_document(payload: dict) -> str:
    return json.dumps(
        {"_generated": BANNER, "_source": SOURCE_LINE, "handle": payload}, indent=2, sort_keys=True
    ) + "\n"


