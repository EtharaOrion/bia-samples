#!/usr/bin/env python3
"""Derive every generated artifact of OER-18 from solution/grounding.yaml alone.

Generated by this file, from that single source:

    tests/benchmark.json            the frozen held-out split
    environment/dev_benchmark.json  the agent-visible development split
    tests/fixtures/*.json           the checker fixtures, one accepting and one rejecting
    tests/test_output.py            the compiled tests tests/checkers.yaml names
    solution/reference.py           the reference generator the live checkers accept
    solution/solve.sh               the reference entry point
    solution/TRUTH.md               the private write-up
    solution/rubrics.json           the solution-against-reference rubric set
    solution/golden_trajectory.json the golden trajectory

No model is invoked, no socket is opened, no clock is read, no locale-dependent operation
is performed, and no random source is consulted. Every ordering is explicit. Running this
twice over frozen bytes produces byte-identical output, and `--check` proves it without
writing.

RELOCATABILITY. This script writes nothing outside its own bundle. The intermediate
scratch it needs -- the emitted reference module it imports back, the benchmark it reads
back, and the two per-handle working trees -- goes to a private temporary directory that
is removed on exit, or to a caller-supplied `--workdir`. It used to derive that scratch
path from the bundle's position on disk:

    workdir = BUNDLE.parents[2] / "results" / "oer18_recompute"

which made the script un-relocatable in two separate ways. Copied to /tmp, `parents[2]`
resolved to `/` and the script died with PermissionError on `/results`. Left in the real
tree, it wrote `seed/results/oer18_recompute`, an out-of-bundle side effect that no caller
asked for and no `--check` run needs. Neither behaviour is a property of the derivation,
so neither is preserved. The scratch location is not an input to any generated artifact:
running from two different locations produces byte-identical bytes.

Usage:
    python3 solution/recompute.py                  # write
    python3 solution/recompute.py --check          # verify committed bytes match, write nothing
    python3 solution/recompute.py --workdir DIR    # keep the scratch tree at DIR for inspection
"""

