def assert_grammar_agrees(source: dict) -> None:
    """The substrate, the classifier and this source must carry the same grammar."""
    grammar = source["task_grammar"]
    assert tuple(grammar["strata"]) == tuple(sorted(grammar["strata"])), "strata must be sorted"
    assert tuple(grammar["strata"]) == frozen_stack.STRATA, "train_stack strata drifted"
    assert tuple(grammar["strata"]) == strata.STRATA, "classifier strata drifted"
    assert tuple(grammar["strata"]) == checkers.STRATA, "checker strata drifted"
    assert dict(grammar["markers"]) == dict(frozen_stack.MARKERS), "train_stack markers drifted"
    assert dict(grammar["markers"]) == dict(strata.MARKERS), "classifier markers drifted"
    for name, words in grammar["stratum_words"].items():
        assert tuple(words) == tuple(frozen_stack.STRATUM_WORDS[name]), "vocabulary drifted: " + name
    assert tuple(grammar["train_fillers"]) == frozen_stack.TRAIN_FILLERS, "train fillers drifted"
    assert tuple(grammar["eval_fillers"]) == frozen_stack.EVAL_FILLERS, "eval fillers drifted"
    assert tuple(grammar["labels"]) == frozen_stack.LABELS, "labels drifted"


