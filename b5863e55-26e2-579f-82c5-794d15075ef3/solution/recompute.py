TARGETS = {
    "tests/checkers.yaml": gen_checkers_yaml,
    "tests/rubrics.jsonl": gen_rubrics_jsonl,
    "tests/test_output.py": gen_test_output_py,
    "solution/rubrics.json": gen_solution_rubrics_json,
    "solution/TRUTH.md": gen_truth_md,
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if committed bytes differ")
    args = ap.parse_args()
    g = load_grounding()
    drift = []
    for rel, fn in sorted(TARGETS.items()):
        want = fn(g)
        path = os.path.join(ROOT, rel)
        if args.check:
            current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
            if current != want:
                drift.append(rel)
            print(("ok    " if current == want else "DRIFT ") + rel)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8") as handle:
                handle.write(want)
            print("wrote " + rel)
    if args.check and drift:
        print("regeneration drift in: " + ", ".join(drift), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
