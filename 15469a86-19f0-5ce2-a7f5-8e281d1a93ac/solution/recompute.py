def _split_flow(text):
    parts, depth, current, quote = [], 0, [], ""
    for character in text:
        if quote:
            current.append(character)
            if character == quote:
                quote = ""
            continue
        if character in "'\"":
            quote = character
            current.append(character)
            continue
        if character in "[{":
            depth += 1
        elif character in "]}":
            depth -= 1
        if character == "," and depth == 0:
            parts.append("".join(current))
            current = []
            continue
        current.append(character)
    if current:
        parts.append("".join(current))
    return [part.strip() for part in parts if part.strip()]


def _scalar(text):
    text = text.strip()
    if text.startswith("[") and text.endswith("]"):
        inner = text[1:-1].strip()
        return [_scalar(part) for part in _split_flow(inner)] if inner else []
    if text.startswith("{") and text.endswith("}"):
        inner = text[1:-1].strip()
        result = {}
        if inner:
            for part in _split_flow(inner):
                key, _, value = part.partition(":")
                result[key.strip()] = _scalar(value)
        return result
    if len(text) >= 2 and text[0] == text[-1] and text[0] in "'\"":
        return text[1:-1]
    if text in ("null", "~", ""):
        return None
    if text == "true":
        return True
    if text == "false":
        return False
    for caster in (int, float):
        try:
            return caster(text)
        except ValueError:
            pass
    return text


def load_grounding(path):
    """A deterministic reader for the block-mapping subset this grounding file uses."""
    lines = Path(path).read_text(encoding="utf-8").splitlines()
    root = {}
    stack = [(-1, root)]
    index = 0
    while index < len(lines):
        raw = lines[index]
        index += 1
        stripped = raw.strip()
        if not stripped or stripped.startswith("#"):
            continue
        indent = len(raw) - len(raw.lstrip(" "))
        while len(stack) > 1 and indent <= stack[-1][0]:
            stack.pop()
        container = stack[-1][1]
        if stripped.startswith("- "):
            item_text = stripped[2:]
            if isinstance(container, list):
                if ":" in item_text and not item_text.startswith(("[", "{")):
                    item = {}
                    container.append(item)
                    key, _, value = item_text.partition(":")
                    stack.append((indent, item))
                    item[key.strip()] = _scalar(value)
                else:
                    container.append(_scalar(item_text))
            continue
        key, _, value = stripped.partition(":")
        key, value = key.strip(), value.strip()
        if value in (">-", "|", "|-", ">"):
            block = []
            while index < len(lines):
                following = lines[index]
                if following.strip() and (len(following) - len(following.lstrip(" "))) <= indent:
                    break
                block.append(following.strip())
                index += 1
            container[key] = " ".join(part for part in block if part)
            continue
        if not value:
            peek = index
            while peek < len(lines) and not lines[peek].strip():
                peek += 1
            child = [] if peek < len(lines) and lines[peek].strip().startswith("- ") else {}
            container[key] = child
            stack.append((indent, child))
            continue
        container[key] = _scalar(value)
    return root


