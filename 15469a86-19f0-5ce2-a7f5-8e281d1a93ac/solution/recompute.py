def rejecting_fixtures(reference, facts):
    """Each fixture is the reference submission with ONE field changed and nothing else."""
    quantum = facts["quantum"]
    witness = facts["witness"]
    identifiers = facts["identifiers"]
    collisions = {(row["a"], row["b"]): row for row in facts["index"]["collisions"]}

    def variant(**changes):
        payload = json.loads(json.dumps(reference, sort_keys=True))
        payload.update(changes)
        return payload

    # The swapped-in record is itself a record the index collides with something, so the
    # near-miss is a plausible pair rather than an obviously inert identifier. Only the
    # witness member moves; no other byte of the submission does.
    colliding_records = set()
    for pair in collisions:
        colliding_records.add(pair[0])
        colliding_records.add(pair[1])
    left_swap = None
    right_swap = None
    for (a, b) in sorted(collisions):
        if b == witness["b"] and a != witness["a"]:
            left_swap = a
        if a == witness["a"] and b != witness["b"]:
            right_swap = b
    if left_swap is None:
        left_swap = next(
            i for i in identifiers if i in colliding_records and i not in (witness["a"], witness["b"])
        )
    if right_swap is None:
        right_swap = next(
            i
            for i in reversed(identifiers)
            if i in colliding_records and i not in (witness["a"], witness["b"])
        )

    # The refused collision that comes second under the bound ordering. Reporting it moves the
    # witness value alone and is the sharpest test that the maximum, and not merely a
    # near-miss, is what the checker requires.
    ranked = []
    for pair, row in collisions.items():
        if pair == (witness["a"], witness["b"]):
            continue
        ranked.append(((int(row["bands"]), int(row["similarity"]), pair[0], pair[1]), row))
    ranked.sort(key=lambda item: (-item[0][0], -item[0][1], item[0][2], item[0][3]))
    runner_up = None
    for _key, row in ranked:
        if reference and [row["a"], row["b"]] in reference["near_duplicate_pairs"]:
            continue
        runner_up = row
        break

    # A pair the index never places in a common band at all.
    non_collision = None
    for left in range(len(identifiers)):
        for right in range(left + 1, len(identifiers)):
            pair = (identifiers[left], identifiers[right])
            if pair not in collisions:
                non_collision = pair
                break
        if non_collision:
            break

    every_pair = []
    for left in range(len(identifiers)):
        for right in range(left + 1, len(identifiers)):
            every_pair.append([identifiers[left], identifiers[right]])

    guessed = (quantum * 3) // 4

    fixtures = {
        "threshold_minus_one_step": variant(adjudication_threshold=facts["threshold"] - 1),
        "threshold_plus_one_step": variant(adjudication_threshold=facts["threshold"] + 1),
        "threshold_guessed_round": variant(adjudication_threshold=guessed),
        "witness_left_member_swapped": variant(
            collision_witness={
                "a": min(left_swap, witness["b"]),
                "b": max(left_swap, witness["b"]),
                "bands": int(witness["bands"]),
                "similarity": int(witness["similarity"]),
            }
        ),
        "witness_right_member_swapped": variant(
            collision_witness={
                "a": min(witness["a"], right_swap),
                "b": max(witness["a"], right_swap),
                "bands": int(witness["bands"]),
                "similarity": int(witness["similarity"]),
            }
        ),
        "witness_not_a_collision": variant(
            collision_witness={
                "a": non_collision[0],
                "b": non_collision[1],
                "bands": int(witness["bands"]),
                "similarity": int(witness["similarity"]),
            }
        ),
        "witness_runner_up_collision": variant(
            collision_witness={
                "a": str(runner_up["a"]),
                "b": str(runner_up["b"]),
                "bands": int(runner_up["bands"]),
                "similarity": int(runner_up["similarity"]),
            }
        ),
        "every_pair_returned": variant(near_duplicate_pairs=every_pair),
        "no_pair_returned": variant(near_duplicate_pairs=[]),
        "collision_census_inflated": variant(index_collision_count=facts["collision_count"] + 1),
        "candidate_pairs_only": variant(
            near_duplicate_pairs=[list(pair) for pair in facts["baseline_pairs"]]
        ),
    }
    if guessed == facts["threshold"]:
        raise SystemExit("the round guess coincides with the established threshold")
    return fixtures


