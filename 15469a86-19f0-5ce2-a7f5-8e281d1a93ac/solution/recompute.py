def main():
    parser = argparse.ArgumentParser(description="derive the OER-27 generated artifacts")
    parser.add_argument("--emit", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--probe", action="store_true")
    parser.add_argument("--corpus-only", action="store_true")
    args = parser.parse_args()

    grounding = load_grounding(HERE / "grounding.yaml")

    if args.corpus_only:
        records = generate_corpus(grounding)
        (BUNDLE / "environment" / "corpus.jsonl").write_bytes(corpus_bytes(records))
        (BUNDLE / "environment" / "index_spec.json").write_bytes(index_spec_bytes(grounding))
        print("corpus and index specification written")
        return 0

    facts = measure(BUNDLE, grounding)

    if args.probe:
        probe(facts, grounding)
        return 0

    reference_path = BUNDLE / "solution" / "fixtures" / "reference_run" / "submission.json"
    reference = None
    if reference_path.is_file():
        reference = json.loads(reference_path.read_text(encoding="utf-8"))

    payloads = artifacts(BUNDLE, grounding, facts, reference)

    if args.check:
        drift = []
        for path, payload in sorted(payloads.items()):
            current = path.read_bytes() if path.is_file() else b""
            if current != payload:
                drift.append(path.relative_to(BUNDLE).as_posix())
        if drift:
            print(json.dumps({"drift": drift}, indent=2, sort_keys=True))
            return 1
        print(json.dumps({"drift": []}, sort_keys=True))
        return 0

    for path, payload in sorted(payloads.items()):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(payload)
    print(
        json.dumps(
            {"written": sorted(p.relative_to(BUNDLE).as_posix() for p in payloads)},
            indent=2,
            sort_keys=True,
        )
    )
    return 0


