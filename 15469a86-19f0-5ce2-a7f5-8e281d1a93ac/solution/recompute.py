def build_vocabulary(spec):
    onsets, nuclei, codas = list(spec["onsets"]), list(spec["nuclei"]), list(spec["codas"])
    words = []
    for position in range(int(spec["word_count"])):
        onset = onsets[position % len(onsets)]
        nucleus = nuclei[(position // len(onsets)) % len(nuclei)]
        coda = codas[(position // (len(onsets) * len(nuclei))) % len(codas)]
        words.append(onset + nucleus + coda)
    return words


def render(tokens, stream, grounding):
    """Turn a token list into a record's raw text. Casing and punctuation are noise."""
    corpus = grounding["corpus"]
    casing = corpus["casing_noise_rate"]
    marks = list(corpus["punctuation_marks"])
    pieces = []
    for position, token in enumerate(tokens):
        word = token
        if next(stream) % int(casing["denominator"]) < int(casing["numerator"]):
            word = word.capitalize()
        pieces.append(word)
        if position + 1 < len(tokens) and next(stream) % 9 == 0:
            pieces.append(marks[next(stream) % len(marks)])
    text = ""
    for piece in pieces:
        if piece in marks and piece.strip():
            text = text.rstrip() + piece.strip() + " "
        else:
            text += piece + " "
    return text.strip() + "."


def draw_document(stream, slice_words, function_words, grounding):
    corpus = grounding["corpus"]
    length_spec = corpus["document_length"]
    rate = corpus["function_word_rate"]
    length = int(length_spec["base"]) + next(stream) % int(length_spec["modulus"])
    tokens = []
    for _ in range(length):
        if next(stream) % int(rate["denominator"]) < int(rate["numerator"]):
            tokens.append(function_words[next(stream) % len(function_words)])
        else:
            tokens.append(slice_words[next(stream) % len(slice_words)])
    return tokens


def edit_document(tokens, numerator, denominator, stream, slice_words):
    """Substitute tokens at the given rate, with an occasional insertion."""
    edited = []
    for token in tokens:
        if next(stream) % denominator < numerator:
            edited.append(slice_words[next(stream) % len(slice_words)])
        else:
            edited.append(token)
        if next(stream) % (denominator * 3) < numerator:
            edited.append(slice_words[next(stream) % len(slice_words)])
    return edited


def generate_corpus(grounding):
    corpus_spec = grounding["corpus"]
    vocabulary = build_vocabulary(corpus_spec["vocabulary"])
    function_words = list(corpus_spec["function_words"])
    slice_width = int(corpus_spec["slice_width"])
    families = corpus_spec["families"]
    edit_rate = corpus_spec["edit_rate"]
    stream = nd_index.lcg_stream(int(corpus_spec["seed"]))

    groups = []
    groups.extend([2] * int(families["pair_families"]))
    groups.extend([3] * int(families["triple_families"]))
    groups.extend([4] * int(families["quad_families"]))
    groups.extend([1] * int(families["singletons"]))

    records = []
    for group_index, size in enumerate(groups):
        start = (group_index * 17) % (len(vocabulary) - slice_width)
        slice_words = vocabulary[start : start + slice_width]
        root = draw_document(stream, slice_words, function_words, grounding)
        members = [root]
        for _ in range(size - 1):
            numerator = int(edit_rate["numerator_base"]) + next(stream) % int(
                edit_rate["numerator_modulus"]
            )
            members.append(
                edit_document(root, numerator, int(edit_rate["denominator"]), stream, slice_words)
            )
        for member in members:
            records.append(render(member, stream, grounding))

    total = int(corpus_spec["record_count"])
    if len(records) != total:
        raise SystemExit(
            "the family plan yields " + str(len(records)) + " records against " + str(total)
        )
    # The corpus is emitted in an order that does not follow the family plan, so family
    # membership is not readable off the identifier sequence.
    permuted = [None] * total
    positions = list(range(total))
    for slot in range(total - 1, 0, -1):
        pick = next(stream) % (slot + 1)
        positions[slot], positions[pick] = positions[pick], positions[slot]
    for source, destination in enumerate(positions):
        permuted[destination] = records[source]
    return [{"id": "r" + str(p).zfill(4), "text": permuted[p]} for p in range(total)]


def corpus_bytes(records):
    return (
        "\n".join(json.dumps(row, sort_keys=True, ensure_ascii=True) for row in records) + "\n"
    ).encode("utf-8")


def index_spec_bytes(grounding):
    spec = grounding["index_spec"]
    payload = {
        "schema": spec["schema"],
        "shingle_order": int(spec["shingle_order"]),
        "similarity_quantum": int(spec["similarity_quantum"]),
        "signature_length": int(spec["signature_length"]),
        "bands": int(spec["bands"]),
        "rows_per_band": int(spec["rows_per_band"]),
        "permutation_seed_source": spec["permutation_seed_source"],
    }
    return (json.dumps(payload, indent=2, sort_keys=True) + "\n").encode("utf-8")


