def sha256_of(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def measure(bundle, grounding):
    corpus_path = Path(bundle) / "environment" / "corpus.jsonl"
    spec_path = Path(bundle) / "environment" / "index_spec.json"
    index = nd_index.build(corpus_path, spec_path)
    quantum = int(index["spec"]["similarity_quantum"])
    threshold = int(index["calibration"]["adjudication_threshold"])

    shingle_sets = {row["id"]: set(row["shingles"]) for row in index["records"]}
    identifiers = [row["id"] for row in index["records"]]

    edges = []
    for left in range(len(identifiers)):
        a = identifiers[left]
        set_a = shingle_sets[a]
        for right in range(left + 1, len(identifiers)):
            b = identifiers[right]
            if nd_index.quantised_similarity(set_a, shingle_sets[b], quantum) >= threshold:
                edges.append((a, b))

    parent = {identifier: identifier for identifier in identifiers}

    def find(node):
        while parent[node] != node:
            parent[node] = parent[parent[node]]
            node = parent[node]
        return node

    for a, b in edges:
        root_a, root_b = find(a), find(b)
        if root_a != root_b:
            parent[root_a] = root_b

    members = {}
    for identifier in identifiers:
        members.setdefault(find(identifier), []).append(identifier)

    truth = set()
    group_sizes = {}
    group_count = 0
    for group in members.values():
        group = sorted(group)
        if len(group) > 1:
            group_count += 1
            group_sizes[len(group)] = group_sizes.get(len(group), 0) + 1
        for left in range(len(group)):
            for right in range(left + 1, len(group)):
                truth.add((group[left], group[right]))

    labels = {identifier: find(identifier) for identifier in identifiers}
    collisions = {(row["a"], row["b"]): row for row in index["collisions"]}
    baseline_pairs = sorted(
        pair for pair, row in collisions.items() if int(row["similarity"]) >= threshold
    )

    witness = None
    witness_key = None
    for pair, row in collisions.items():
        if labels[pair[0]] == labels[pair[1]]:
            continue
        key = (int(row["bands"]), int(row["similarity"]), pair[0], pair[1])
        if witness_key is None or key[:2] > witness_key[:2] or (
            key[:2] == witness_key[:2] and key[2:] < witness_key[2:]
        ):
            witness, witness_key = row, key

    shard_count = int(grounding["shards"]["count"])
    record_count = len(identifiers)
    width = max(1, record_count // shard_count)
    shard_totals = {}
    shard_baseline = {}
    baseline_set = set(baseline_pairs)
    for pair in truth:
        shard = min(int(pair[0][1:]) // width, shard_count - 1)
        shard_totals[shard] = shard_totals.get(shard, 0) + 1
        if pair in baseline_set:
            shard_baseline[shard] = shard_baseline.get(shard, 0) + 1

    baseline_hits = len(baseline_set & truth)
    return {
        "index": index,
        "quantum": quantum,
        "threshold": threshold,
        "separation_split": int(index["calibration"]["separation_split"]),
        "identifiers": identifiers,
        "record_count": record_count,
        "edges": sorted(edges),
        "truth_pairs": sorted(truth),
        "duplicate_group_count": group_count,
        "group_sizes": group_sizes,
        "collision_count": len(collisions),
        "baseline_pairs": baseline_pairs,
        "baseline_recall": round(baseline_hits / len(truth), 6) if truth else 0.0,
        "witness": witness,
        "shard_totals": shard_totals,
        "shard_baseline": shard_baseline,
        "corpus_sha256": sha256_of(corpus_path),
        "index_spec_sha256": sha256_of(spec_path),
    }


